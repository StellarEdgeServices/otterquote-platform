#!/usr/bin/env python3
"""gh-3239 (#3238): render Partner Referral Agreement v4-2026-10 into partner-agreement.html.

Single source: docs/legal/partner-agreement-v4-2026-10.md (verbatim publishable text; wording is LEGAL-READ owned).
This script rewrites ONLY the block between the BEGIN/END markers inside .legal-content of partner-agreement.html.
It changes no words. The markdown it understands is exactly what the source uses:
  "# title" and the line after it   -> must equal the page hero (checked, not re-rendered)
  "## x" / "### x"                  -> <section><h2> / <h3>
  "> **Label**" + "> text" lines    -> <div class="disclaimer-box"><h3>Label</h3><p>text</p></div>
  "- item" lines                    -> <ul><li>
  any other line                    -> <p>
  **x** -> <strong>, [t](u) -> <a href="u">t</a>; &, <, > escaped.
Presentation-only additions (no new words):
  - the home-inspector track hide (gh-2155 HI-0b; CSS :target + the ?track= script already on the page) covers the same
    elements as on v3: the Section 4 fee block (Section 4's text up to its first ###), Section 4.1, all of Section 7, and the
    Section 14(a) cross-reference to Section 7;
  - in Section 8.2 the words "Otter Quotes Creator Guide" link to #creator-guide-pending: Creator Guide v2-2026-10 is not filed
    yet, so the link is a placeholder to repoint when it is.
Usage: python3 scripts/render-partner-agreement.py [--check]   (--check exits 1 if the page is out of date)
"""
import html
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "docs/legal/partner-agreement-v4-2026-10.md"
PAGE = ROOT / "partner-agreement.html"
BEGIN = "<!-- BEGIN gh3239 AGREEMENT-V4 (generated by scripts/render-partner-agreement.py from docs/legal/partner-agreement-v4-2026-10.md; do not hand-edit) -->"
END = "<!-- END gh3239 AGREEMENT-V4 -->"
HERO_TITLE = "Partner Referral Agreement"
HERO_SUB = "Terms governing your participation in the Otter Quotes Partner Referral Program"
CREATOR_GUIDE = "Otter Quotes Creator Guide"
S14A = ", including the representation in Section 7 that Partner has confirmed Partner&#x27;s own eligibility to accept referral fees"


def inline(text: str) -> str:
    out = html.escape(text, quote=False).replace("'", "&#x27;")
    out = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", out)
    out = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", lambda m: f'<a href="{m.group(2)}">{m.group(1)}</a>', out)
    return out


def blocks(lines):
    """Group lines into (kind, payload) blocks."""
    out, i = [], 0
    while i < len(lines):
        ln = lines[i]
        if not ln.strip():
            i += 1
            continue
        if ln.startswith("### "):
            out.append(("h3", ln[4:])); i += 1
        elif ln.startswith("## "):
            out.append(("h2", ln[3:])); i += 1
        elif ln.startswith(">"):
            q = []
            while i < len(lines) and lines[i].startswith(">"):
                q.append(lines[i][1:].strip()); i += 1
            q = [x for x in q if x]
            m = re.fullmatch(r"\*\*(.+)\*\*", q[0])
            if not m:
                raise SystemExit(f"blockquote must open with a **Label** line: {q[0]!r}")
            out.append(("box", (m.group(1), q[1:])))
        elif ln.startswith("- "):
            items = []
            while i < len(lines) and lines[i].startswith("- "):
                items.append(lines[i][2:]); i += 1
            out.append(("ul", items))
        else:
            out.append(("p", ln)); i += 1
    return out


def render(md: str) -> str:
    body = re.sub(r"^<!--.*?-->\s*", "", md, flags=re.S)
    lines = body.splitlines()
    if lines[0] != f"# {HERO_TITLE}":
        raise SystemExit("source title no longer matches the page hero")
    rest = [l for l in lines[1:]]
    first_text = next(l for l in rest if l.strip())
    if first_text != HERO_SUB:
        raise SystemExit("source subtitle no longer matches the page hero")
    rest.remove(HERO_SUB)
    parts = [BEGIN]
    open_section = False
    section_title = None
    in_fee_block = False
    in_hidden_sub = False

    def close_wrappers():
        nonlocal in_fee_block, in_hidden_sub
        if in_fee_block:
            parts.append("</div>"); in_fee_block = False
        if in_hidden_sub:
            parts.append("</div>"); in_hidden_sub = False

    for kind, val in blocks(rest):
        if kind == "h2":
            close_wrappers()
            if open_section:
                parts.append("</section>")
            section_title = val
            hide = ' class="inspector-hide"' if val.startswith("7. ") else ""
            parts.append(f"<section{hide}>")
            parts.append(f"<h2>{inline(val)}</h2>")
            open_section = True
            if val == "4. Referral Fee Structure":
                parts.append('<div id="feeStructureBlock" class="inspector-hide">')
                in_fee_block = True
            continue
        if kind == "h3":
            close_wrappers()
            if val.startswith("4.1 "):
                parts.append('<div class="inspector-hide">')
                in_hidden_sub = True
            parts.append(f"<h3>{inline(val)}</h3>")
            continue
        if kind == "box":
            label, paras = val
            box_id = ' id="d266DisclaimerBox"' if label == "Mandatory Disclaimer" else ""
            parts.append(f'<div class="disclaimer-box"{box_id}>')
            parts.append(f"<h3>{inline(label)}</h3>")
            parts += [f"<p>{inline(p)}</p>" for p in paras]
            parts.append("</div>")
            continue
        if kind == "ul":
            parts.append("<ul>")
            parts += [f"<li>{inline(it)}</li>" for it in val]
            parts.append("</ul>")
            continue
        p = inline(val)
        if not open_section:
            m = re.fullmatch(r"<strong>(Effective Date|Version):</strong> (.+)", p)
            if m:
                key = "agreementEffectiveDate" if m.group(1) == "Effective Date" else "agreementVersion"
                p = f'<strong>{m.group(1)}:</strong> <span id="{key}">{m.group(2)}</span>'
        if section_title and section_title.startswith("8. ") and CREATOR_GUIDE in p:
            p = p.replace(CREATOR_GUIDE, f'<a href="#creator-guide-pending" data-placeholder="creator-guide-v2-2026-10">{CREATOR_GUIDE}</a>', 1)
        if section_title and section_title.startswith("14. "):
            if S14A not in p:
                raise SystemExit("Section 14(a) cross-reference to Section 7 not found")
            p = p.replace(S14A, f'<span class="inspector-hide">{S14A}</span>', 1)
        parts.append(f"<p>{p}</p>")
    close_wrappers()
    if open_section:
        parts.append("</section>")
    parts.append(END)
    return "\n".join(parts)


def main() -> int:
    md = SRC.read_text(encoding="utf-8")
    page = PAGE.read_text(encoding="utf-8")
    if page.count(BEGIN) != 1 or page.count(END) != 1:
        print("partner-agreement.html must hold exactly one BEGIN and one END marker", file=sys.stderr)
        return 2
    a = page.index(BEGIN)
    b = page.index(END) + len(END)
    new = page[:a] + render(md) + page[b:]
    if "--check" in sys.argv:
        if new != page:
            print("partner-agreement.html is out of date: run python3 scripts/render-partner-agreement.py", file=sys.stderr)
            return 1
        print("partner-agreement.html agreement block is current")
        return 0
    PAGE.write_text(new, encoding="utf-8")
    print("rendered", SRC.relative_to(ROOT), "->", PAGE.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
