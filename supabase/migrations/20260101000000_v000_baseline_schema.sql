CREATE OR REPLACE FUNCTION public.record_attestation_ip(p_contractor_id uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_ip TEXT;
  v_ua TEXT;
  v_headers JSONB;
