-- v000_baseline_schema.sql
--
-- Schema-only baseline for issue #385 (supabase/migrations reconciliation).
--
-- WHY THIS EXISTS: the live production ledger (yeszghaspzwwstvsrioa,
-- "Claim Shield") has 82+ applied migrations, but ~62 of them --
-- including effectively the entire foundational schema (v53-v81 and
-- others) -- were applied directly to production and never committed
-- to this repo (see supabase/migrations/MIGRATIONS-RECONCILIATION-385.md
-- for the full audit trail from PR #666). A genuinely fresh database
-- has zero public tables and every `supabase branches create` fails
-- with MIGRATIONS_FAILED as a result.
--
-- THIS IS NOT A pg_dump OUTPUT. HOW IT WAS ACTUALLY CAPTURED:
-- PR #666 identified that closing this gap needs a schema-only
-- `pg_dump` of production. Docker (required by `supabase db dump` /
-- `db reset` to run pg_dump in a version-matched container) was
-- unavailable in that session and remains unavailable in this one --
-- confirmed via `docker info`, a Docker Desktop restart attempt that
-- crashed, and a direct check inside the `docker-desktop` WSL distro
-- (no dockerd process, no dockerd binary present). No native
-- pg_dump/psql client is installed on this machine either.
--
-- In place of pg_dump, this file was generated by read-only catalog
-- introspection: a script queried pg_catalog / information_schema on
-- the live production database directly (via the Supabase Management
-- API, bypassing the Docker-dependent CLI path) and used Postgres's
-- own DDL-reconstruction functions -- pg_get_constraintdef,
-- pg_get_indexdef, pg_get_functiondef, pg_get_triggerdef,
-- pg_get_viewdef -- to emit this file mechanically, not by hand.
-- Because this is introspection rather than a literal pg_dump, one
-- ordering issue specific to this method had to be found and fixed:
-- LANGUAGE SQL functions are parsed/validated at CREATE FUNCTION
-- time (unlike plpgsql, which is opaque text until first execution),
-- so admin_list_referrals and request_is_privileged -- both of which
-- call is_admin_email() in their body -- had to be ordered after it.
-- pg_dump handles this automatically via dependency-graph output;
-- here it was verified by regex-scanning function bodies for calls
-- to other functions in this schema (pg_depend does not track
-- function-to-function call dependencies) and confirmed by two full
-- dry-run replays against a disposable Supabase preview branch.
--
-- VERIFICATION PERFORMED: this exact file was replayed end-to-end
-- against a fresh, empty Supabase preview branch (created via
-- `supabase branches create`, cost ~$0.0134/hr, deleted after
-- verification) and diffed object-by-object against production.
-- Result: tables, views, columns, constraints, indexes, RLS policies,
-- RLS-enabled flags, and triggers were byte-identical. Functions
-- matched on 58 of 59; the one difference (cleanup_old_rate_limits)
-- was a CRLF-vs-LF artifact in MY OWN tooling pipeline (a Python
-- text-mode re-read silently normalized line endings), not a real
-- schema difference -- production's stored function body genuinely
-- contains a literal CRLF sequence, and this file now preserves that
-- byte-for-byte. See the PR/issue for the full diff run and the
-- branch-creation log.
--
-- Object counts (cross-checked against independent catalog COUNT(*)
-- queries and matched exactly): 44 tables, 9 views, 59 functions,
-- 110 RLS policies, 36 triggers, 200 indexes total (141 explicit +
-- 59 backing PK/UNIQUE constraints), 54 foreign keys, 7 extensions
-- (of which uuid-ossp/pgcrypto/pg_net are user-schema-relevant and
-- created below; pg_cron/pg_stat_statements/supabase_vault/plpgsql
-- are Supabase-platform-managed and out of scope for user migrations).
-- Table grants to anon/authenticated/service_role were checked and
-- found to be the uniform Supabase project-default set on every
-- table (no custom REVOKEs) -- these are applied automatically by
-- the platform's default privileges on table creation, not by user
-- migrations, so this file does not re-issue them.
--
-- Captured: 2026-08-11, from yeszghaspzwwstvsrioa (PostgreSQL 17.6.1.084).
--
-- Timestamped before the earliest existing file in this directory
-- (20260519221215) so it replays first on a fresh database, before
-- every migration that already assumes this schema exists. Confirmed
-- clear of every in-flight version collision as of this writing
-- (v102/#660 merged, v105 claimed twice by #703 and #711, v106/#704)
-- since v000 uses an entirely different naming scheme and a
-- timestamp far earlier than any of them.
--
-- After this file is committed, production migration history must
-- be repaired (supabase migration repair --status applied for this
-- version) so this baseline is marked already-applied and never
-- actually replays against production itself -- see the PR/issue
-- for the repair command actually run and its output.
--
-- SECRET REDACTED (found during capture, not introduced by it): GitHub
-- push protection blocked the first push attempt on this file -- it
-- correctly caught a live Supabase secret key hardcoded in production
-- inside the bodies of notify_feature_request_webhook() and
-- notify_hover_rebate() (used to authenticate their net.http_post call
-- to an Edge Function; every other trigger in this schema instead
-- reads current_setting('app.service_role_key', true) at call time --
-- these two are the only ones with the value burned into the source).
-- Both occurrences below are replaced with the placeholder
-- REDACTED_HARDCODED_SECRET_SEE_GH385_ROTATE_AND_MOVE_TO_VAULT, so a
-- database built from this baseline will have a non-functional
-- Authorization header on those two triggers until the real value is
-- restored through Vault / a project secret. Production itself still
-- has the real secret live in these two function bodies as of this
-- writing -- that is a separate, real security issue, flagged
-- out-of-band, not fixed by this PR.

