CREATE OR REPLACE FUNCTION public.apply_referral_commission()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_claim_referral_id   UUID;
  v_referral            public.referrals%ROWTYPE;
  v_referrer            public.referral_agents%ROWTYPE;
  v_recruiter           public.referral_agents%ROWTYPE;
  v_referral_approval   UUID;
  v_recruit_approval    UUID;
  v_supabase_url        TEXT;
  v_service_role_key    TEXT;
BEGIN
  -- 1. Locate the referral via the quote's claim.
  SELECT referral_id INTO v_claim_referral_id
    FROM public.claims
    WHERE id = NEW.claim_id;

  IF v_claim_referral_id IS NULL THEN
    RETURN NEW;
  END IF;

  -- 2. Load and lock the referral row.
  SELECT * INTO v_referral
    FROM public.referrals
    WHERE id = v_claim_referral_id
    FOR UPDATE;

  IF NOT FOUND THEN
    RETURN NEW;
  END IF;

  -- 3. Idempotency: if commission was already applied, do not re-apply.
  IF COALESCE(v_referral.commission_amount, 0) > 0 THEN
    RETURN NEW;
  END IF;

  -- 4. Load the referrer.
  SELECT * INTO v_referrer
    FROM public.referral_agents
    WHERE id = v_referral.referral_agent_id;

  IF NOT FOUND THEN
    RETURN NEW;
  END IF;

  -- 5. Apply the $200 referrer bonus and advance status to 'contract_signed'.
  --    (#567 / D-139 audit: this trigger fires on the fee charge at contract
  --    signing — the previous 'job_completed' label was false. Never downgrade
  --    a referral that already reached job_completed or commission_paid.)
  UPDATE public.referrals
     SET commission_amount = 200,
         job_value         = NEW.total_price,
         status            = CASE
                               WHEN status IN ('job_completed', 'commission_paid')
                                 THEN status
                               ELSE 'contract_signed'
                             END
   WHERE id = v_referral.id;

  -- 6. Insert payout_approval for the referral commission.
  INSERT INTO public.payout_approvals (
    referral_id,
    payout_type,
    partner_id,
    partner_name,
    amount,
    trigger_event,
    status,
    auto_approve_at
  )
  VALUES (
    v_referral.id,
    'commission_referral',
    v_referrer.id,
    TRIM(COALESCE(v_referrer.first_name, '') || ' ' || COALESCE(v_referrer.last_name, '')),
    200,
    'Fee charged — referral ' || v_referral.id::TEXT || ' (quote ' || NEW.id::TEXT || ')',
    'pending_approval',
    NOW() + INTERVAL '7 days'
  )
  RETURNING id INTO v_referral_approval;

  -- 7. Forward-only recruit bonus per D-142.
  IF v_referrer.recruited_by_id IS NOT NULL
     AND v_referrer.recruited_at IS NOT NULL
     AND v_referral.created_at >= v_referrer.recruited_at THEN

    UPDATE public.referrals
       SET recruit_commission_amount = 50
     WHERE id = v_referral.id;

    UPDATE public.referral_agents
       SET recruit_earnings = COALESCE(recruit_earnings, 0) + 50
     WHERE id = v_referrer.recruited_by_id;

    -- Load recruiter name for the approval row.
    SELECT * INTO v_recruiter
      FROM public.referral_agents
      WHERE id = v_referrer.recruited_by_id;

    -- Insert payout_approval for the recruit commission.
    INSERT INTO public.payout_approvals (
      referral_id,
      payout_type,
      partner_id,
      partner_name,
      amount,
      trigger_event,
      status,
      auto_approve_at
    )
    VALUES (
      v_referral.id,
      'commission_recruit',
      v_referrer.recruited_by_id,
      TRIM(COALESCE(v_recruiter.first_name, '') || ' ' || COALESCE(v_recruiter.last_name, '')),
      50,
      'Recruit bonus — referral ' || v_referral.id::TEXT || ' (referrer: ' || TRIM(COALESCE(v_referrer.first_name, '') || ' ' || COALESCE(v_referrer.last_name, '')) || ')',
      'pending_approval',
      NOW() + INTERVAL '7 days'
    )
    RETURNING id INTO v_recruit_approval;
  END IF;

  -- 8. Fire notify-payout-pending via pg_net (async, fire-and-forget).
  --    If pg_net is not available or the call fails, the EXCEPTION handler
  --    below swallows it — payment integrity is never at risk.
  --    The notify-payout-pending function also tolerates duplicate calls
  --    (idempotent via notification_sent_at).
  BEGIN
    v_supabase_url      := current_setting('app.supabase_url',      true);
    v_service_role_key  := current_setting('app.service_role_key',  true);

    IF v_supabase_url IS NOT NULL AND v_service_role_key IS NOT NULL
       AND v_referral_approval IS NOT NULL THEN
      PERFORM net.http_post(
        url     := v_supabase_url || '/functions/v1/notify-payout-pending',
        headers := jsonb_build_object(
          'Content-Type',  'application/json',
          'Authorization', 'Bearer ' || v_service_role_key
        ),
        body    := jsonb_build_object(
          'payout_approval_id', v_referral_approval
        )
      );
    END IF;
  EXCEPTION
    WHEN OTHERS THEN
      RAISE LOG 'apply_referral_commission: pg_net call to notify-payout-pending failed (non-fatal). approval_id=% sqlstate=% sqlerrm=%',
        v_referral_approval, SQLSTATE, SQLERRM;
  END;

  RETURN NEW;

EXCEPTION
  -- Never allow a commission-side failure to roll back the payment itself.
  WHEN OTHERS THEN
    RAISE LOG 'apply_referral_commission failed for quote_id=% claim_id=% sqlstate=% sqlerrm=%',
      NEW.id, NEW.claim_id, SQLSTATE, SQLERRM;
    RETURN NEW;
END;
$function$
;

CREATE OR REPLACE FUNCTION public.bid_can_submit(p_contractor_id uuid, p_trade text, p_funding_type text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_status text;
  v_reason text;
  v_can_submit boolean := false;
BEGIN
  -- Input validation
  IF p_contractor_id IS NULL THEN
    RETURN jsonb_build_object('can_submit', false, 'reason', 'contractor_id required', 'status', NULL);
  END IF;
  IF p_trade IS NULL OR length(trim(p_trade)) = 0 THEN
    RETURN jsonb_build_object('can_submit', false, 'reason', 'trade required', 'status', NULL);
  END IF;
  IF p_funding_type IS NULL OR length(trim(p_funding_type)) = 0 THEN
    RETURN jsonb_build_object('can_submit', false, 'reason', 'funding_type required', 'status', NULL);
  END IF;

  -- Look up the contractor_templates row for this slot (case-insensitive)
  SELECT status INTO v_status
  FROM public.contractor_templates
  WHERE contractor_id = p_contractor_id
    AND lower(trade) = lower(p_trade)
    AND lower(funding_type) = lower(p_funding_type)
  LIMIT 1;

  IF v_status IS NULL THEN
    RETURN jsonb_build_object(
      'can_submit', false,
      'reason', 'Your contract template for ' || initcap(p_trade) || ' / ' || initcap(p_funding_type) || ' has not been uploaded yet. Upload and validate it on your profile before bidding.',
      'status', 'not_found'
    );
  END IF;

  -- Status mapping (matches js/contract-template-validation.js status set)
  CASE v_status
    WHEN 'auto_validated', 'manual_validated', 'admin_validated' THEN
      v_can_submit := true;
      v_reason := NULL;
    WHEN 'pending_validation' THEN
      v_reason := 'Your contract template for ' || initcap(p_trade) || ' / ' || initcap(p_funding_type) || ' is still being validated. Refresh in a moment or check your profile.';
    WHEN 'manual_mapping_pending' THEN
      v_reason := 'Your contract template for ' || initcap(p_trade) || ' / ' || initcap(p_funding_type) || ' needs your action — please complete the manual anchor mapping on your profile.';
    WHEN 'submitted_for_admin_review' THEN
      v_reason := 'Your contract template for ' || initcap(p_trade) || ' / ' || initcap(p_funding_type) || ' is in admin review. You will be notified once approved.';
    WHEN 'rejected' THEN
      v_reason := 'Your contract template for ' || initcap(p_trade) || ' / ' || initcap(p_funding_type) || ' was rejected. Please re-upload a corrected template on your profile.';
    ELSE
      v_reason := 'Template status (' || v_status || ') does not permit bidding. Contact support if you believe this is an error.';
  END CASE;

  RETURN jsonb_build_object(
    'can_submit', v_can_submit,
    'reason', v_reason,
    'status', v_status
  );
END;
