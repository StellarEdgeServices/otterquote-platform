-- Write guard + history archiver.
CREATE OR REPLACE FUNCTION public.referral_agents_guard_vanity_slug()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $fn$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.vanity_slug IS NOT NULL
       AND auth.role() IS DISTINCT FROM 'service_role'
       AND NOT COALESCE(public.is_admin_email(), false)
       AND COALESCE(current_setting('oq.p18_slug_write', true), '') <> '1' THEN
      RAISE EXCEPTION 'referral_agents: vanity_slug can only be set through set_partner_slug() (P18)'
        USING ERRCODE = '42501';
    END IF;
    RETURN NEW;
  END IF;

  IF NEW.vanity_slug IS DISTINCT FROM OLD.vanity_slug THEN
    IF COALESCE(
         auth.role() IS DISTINCT FROM 'service_role'
         AND NOT COALESCE(public.is_admin_email(), false)
         AND COALESCE(current_setting('oq.p18_slug_write', true), '') <> '1',
         true
       ) THEN
      RAISE EXCEPTION 'referral_agents: vanity_slug can only be set through set_partner_slug() (P18)'
        USING ERRCODE = '42501';
    END IF;
    IF OLD.vanity_slug IS NOT NULL THEN
      INSERT INTO public.referral_agent_slug_history (referral_agent_id, slug)
      VALUES (OLD.id, OLD.vanity_slug)
      ON CONFLICT DO NOTHING;
    END IF;
  END IF;
  RETURN NEW;
END;
$fn$;
REVOKE ALL ON FUNCTION public.referral_agents_guard_vanity_slug() FROM PUBLIC, anon, authenticated;

CREATE TRIGGER referral_agents_guard_vanity_slug
  BEFORE INSERT OR UPDATE ON public.referral_agents
  FOR EACH ROW EXECUTE FUNCTION public.referral_agents_guard_vanity_slug();

-- The picker's RPC.
CREATE OR REPLACE FUNCTION public.set_partner_slug(p text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $fn$
DECLARE
  v_uid   uuid := auth.uid();
  v_agent public.referral_agents%ROWTYPE;
  s       text;
  v_taken constant text := 'That short link is not available. Please try another.';
  v_bad   text;
BEGIN
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'Please sign in to choose a short link.' USING ERRCODE = '42501', HINT = 'not_signed_in';
  END IF;

  SELECT * INTO v_agent FROM public.referral_agents WHERE user_id = v_uid FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'No partner account was found for this sign-in.' USING ERRCODE = 'P0002', HINT = 'no_partner';
  END IF;
  IF v_agent.status IS DISTINCT FROM 'active' THEN
    RAISE EXCEPTION 'Your partner account is not active yet.' USING ERRCODE = '42501', HINT = 'not_active';
  END IF;

  IF p IS NULL THEN
    RAISE EXCEPTION 'Enter a short link.' USING ERRCODE = '22023', HINT = 'empty';
  END IF;
  s := lower(p);

  IF char_length(s) < 3 THEN
    RAISE EXCEPTION 'Use at least 3 characters.' USING ERRCODE = '22023', HINT = 'too_short';
  END IF;
  IF char_length(s) > 30 THEN
    RAISE EXCEPTION 'Use 30 characters or fewer.' USING ERRCODE = '22023', HINT = 'too_long';
  END IF;
  IF s !~ '^[a-z0-9-]+$' THEN
    RAISE EXCEPTION 'Use only letters, numbers and hyphens.' USING ERRCODE = '22023', HINT = 'bad_chars';
  END IF;
  IF left(s, 1) = '-' OR right(s, 1) = '-' OR position('--' in s) > 0 THEN
    RAISE EXCEPTION 'Hyphens cannot start or end the link or appear twice in a row.' USING ERRCODE = '22023', HINT = 'bad_hyphen';
  END IF;
  IF s ~ '^[0-9]+$' THEN
    RAISE EXCEPTION 'Include at least one letter.' USING ERRCODE = '22023', HINT = 'all_digits';
  END IF;

  -- Serialize slug claims so two partners cannot both pass the checks below for one slug.
  PERFORM pg_advisory_xact_lock(hashtext('p18_vanity_slug'));

  IF EXISTS (SELECT 1 FROM public.reserved_slugs r WHERE lower(r.slug) = s) THEN
    RAISE EXCEPTION '%', v_taken USING ERRCODE = '22023', HINT = 'unavailable';
  END IF;

  -- Profanity / brand impersonation: substring match on the hyphen-stripped slug.
  v_bad := replace(s, '-', '');
  IF v_bad ~ '(fuck|shit|cunt|bitch|nigg|fagg|asshole|whore|nazi|rapist|otterquote|stellaredge|officialotter|otterofficial|official|staff|customerservice|customersupport|claimsdesk)' THEN
    RAISE EXCEPTION '%', v_taken USING ERRCODE = '22023', HINT = 'unavailable';
  END IF;

  IF EXISTS (SELECT 1 FROM public.referral_agents a
              WHERE lower(a.unique_code) = s OR lower(COALESCE(a.recruit_code, '')) = s)
     OR EXISTS (SELECT 1 FROM public.referral_agents a
                 WHERE lower(a.vanity_slug) = s AND a.id <> v_agent.id)
     OR EXISTS (SELECT 1 FROM public.referral_agent_slug_history h
                 WHERE lower(h.slug) = s AND h.referral_agent_id <> v_agent.id) THEN
    RAISE EXCEPTION '%', v_taken USING ERRCODE = '22023', HINT = 'unavailable';
  END IF;

  IF lower(COALESCE(v_agent.vanity_slug, '')) = s THEN
    RETURN jsonb_build_object('slug', s, 'changed', false);
  END IF;

  -- Re-claiming one of the caller's own retired slugs takes it back out of history.
  DELETE FROM public.referral_agent_slug_history
   WHERE referral_agent_id = v_agent.id AND lower(slug) = s;

  PERFORM set_config('oq.p18_slug_write', '1', true);
  UPDATE public.referral_agents SET vanity_slug = s WHERE id = v_agent.id;
  PERFORM set_config('oq.p18_slug_write', '', true);

  RETURN jsonb_build_object('slug', s, 'changed', true);
END;
$fn$;
REVOKE ALL ON FUNCTION public.set_partner_slug(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.set_partner_slug(text) TO authenticated, service_role;

COMMIT;
